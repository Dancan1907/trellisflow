// ============================================================================
// Reports Service
// ============================================================================

import { Injectable } from '@nestjs/common';
import { PrismaService } from '../../prisma/prisma.service';
import * as PDFDocument from 'pdfkit';

@Injectable()
export class ReportsService {
  constructor(private prisma: PrismaService) {}

  /**
   * 1. Net Worth Trend (for the dashboard chart)
   */
  async getNetWorthTrend(userId: string, days: number = 30) {
    const startDate = new Date();
    startDate.setDate(startDate.getDate() - days);

    return this.prisma.netWorthSnapshot.findMany({
      where: {
        userId,
        date: { gte: startDate },
      },
      orderBy: { date: 'asc' },
      select: {
        date: true,
        totalNetWorth: true,
        personalNetWorth: true,
        investmentsNetWorth: true,
        businessesNetWorth: true,
      },
    });
  }

  /**
   * 2. Cash Flow Report (Income vs Expenses for a date range)
   */
  async getCashFlow(userId: string, dateFrom: Date, dateTo: Date) {
    const transactions = await this.prisma.transaction.findMany({
      where: {
        userId,
        date: { gte: dateFrom, lte: dateTo },
        deletedAt: null,
      },
    });

    let income = 0;
    let expenses = 0;

    for (const tx of transactions) {
      if (tx.type === 'INCOME') income += Number(tx.amount);
      if (tx.type === 'EXPENSE') expenses += Number(tx.amount);
    }

    return {
      period: { from: dateFrom, to: dateTo },
      income,
      expenses,
      net: income - expenses,
    };
  }

  /**
   * 3. Allocation Report (Breakdown by Container)
   */
  async getAllocation(userId: string) {
    // Get latest snapshot to see breakdown
    const latest = await this.prisma.netWorthSnapshot.findFirst({
      where: { userId },
      orderBy: { date: 'desc' },
    });

    if (!latest) {
      return { message: 'No snapshots found yet.' };
    }

    return {
      total: latest.totalNetWorth,
      breakdown: {
        personal: latest.personalNetWorth,
        investments: latest.investmentsNetWorth,
        businesses: latest.businessesNetWorth,
      },
    };
  }

  /**
   * Generate a Net Worth PDF statement.
   */
  async generateNetWorthPDF(userId: string): Promise<Buffer> {
    // 1. Fetch the latest snapshot and user details
    const latest = await this.prisma.netWorthSnapshot.findFirst({
      where: { userId },
      orderBy: { date: 'desc' },
    });
    const user = await this.prisma.user.findUnique({
      where: { id: userId },
    });
    if (!latest || !user) {
      throw new Error('No data available to generate PDF');
    }
    // 2. Create the PDF document
    return new Promise((resolve, reject) => {
      const doc = new PDFDocument({ margin: 50 });
      const chunks: Buffer[] = [];
      doc.on('data', (chunk) => chunks.push(chunk));
      doc.on('end', () => resolve(Buffer.concat(chunks)));
      doc.on('error', reject);
      // 3. Draw the PDF
      doc.fontSize(20).text('TrellisFlow', { align: 'center' });
      doc.fontSize(14).text('Net Worth Statement', { align: 'center' });
      doc.moveDown();
      doc.fontSize(10).text(`Prepared for: ${user.name} (${user.email})`);
      doc.text(`Report Date: ${latest.date.toISOString().split('T')[0]}`);
      doc.moveDown();
      doc.fontSize(12).text('Summary', { underline: true });
      doc.moveDown(0.5);
      doc
        .fontSize(10)
        .text(
          `Total Net Worth: ${latest.currency} ${Number(latest.totalNetWorth).toLocaleString()}`,
        );
      doc.text(`Personal: ${latest.currency} ${Number(latest.personalNetWorth).toLocaleString()}`);
      doc.text(
        `Investments: ${latest.currency} ${Number(latest.investmentsNetWorth).toLocaleString()}`,
      );
      doc.text(
        `Businesses: ${latest.currency} ${Number(latest.businessesNetWorth).toLocaleString()}`,
      );
      doc.moveDown();
      doc
        .fontSize(8)
        .fillColor('gray')
        .text('Generated by TrellisFlow. All rights reserved.', { align: 'center' });
      doc.end();
    });
  }
}
